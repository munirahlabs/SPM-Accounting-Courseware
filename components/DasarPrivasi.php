    // Adjust the anchor offset based on actual navigation height
    document.addEventListener('DOMContentLoaded', function() {
      // Get the navigation bar height
      const navBar = document.querySelector('nav') || document.querySelector('header');
      let navHeight = 120; // default height
      
      if (navBar) {
        navHeight = navBar.offsetHeight;
      }
      
      // Update CSS variables
      document.documentElement.style.scrollPaddingTop = navHeight + 'px';
      
      // Update all anchor offsets
      const anchors = document.querySelectorAll('.anchor-offset');
      anchors.forEach(anchor => {
        anchor.style.top = '-' + navHeight + 'px';
      });
      
      // Update TOC sticky position
      const toc = document.querySelector('.toc');
      if (toc) {
        toc.style.top = (navHeight + 10) + 'px';
      }
      
      // Update heading padding/margin
      const headings = document.querySelectorAll('h1, h2, h3');
      headings.forEach(heading => {
        heading.style.paddingTop = '20px';
        heading.style.marginTop = '-20px';
      });
    });

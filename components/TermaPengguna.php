  <script>
    // Initialize when page loads
    document.addEventListener('DOMContentLoaded', function() {
      // Adjust anchors based on actual navigation height
      adjustAnchorOffsets();
      
      // Set up TOC active state tracking
      setupTocActiveState();
      
      // Set up smooth scrolling for TOC links
      setupSmoothScrolling();
      
      // Listen for window resize to adjust anchors
      window.addEventListener('resize', adjustAnchorOffsets);
    });
    
    function adjustAnchorOffsets() {
      // Estimate navigation height (adjust if you know exact height)
      let navHeight = 120; // Default
      
      // Try to get actual nav height if possible
      const navElements = document.querySelectorAll('nav, header, .navbar');
      if (navElements.length > 0) {
        // Get the first nav element
        const navElement = navElements[0];
        const rect = navElement.getBoundingClientRect();
        navHeight = rect.height;
      }
      
      // Update CSS scroll padding
      document.documentElement.style.scrollPaddingTop = navHeight + 'px';
      
      // Update all anchor offsets
      const anchors = document.querySelectorAll('.anchor-offset');
      anchors.forEach(anchor => {
        anchor.style.top = '-' + navHeight + 'px';
      });
      
      // Update TOC sticky position
      const toc = document.querySelector('.toc');
      if (toc) {
        toc.style.top = (navHeight + 10) + 'px';
      }
    }
    
    function setupTocActiveState() {
      const sections = document.querySelectorAll('h3');
      const tocLinks = document.querySelectorAll('.toc a');
      
      // Helper to remove active class from all links
      function removeActiveClasses() {
        tocLinks.forEach(link => {
          link.classList.remove('active');
        });
      }
      
      // Check which section is in view
      function checkActiveSection() {
        let currentSectionId = '';
        
        sections.forEach(section => {
          const rect = section.getBoundingClientRect();
          const navHeight = parseInt(document.documentElement.style.scrollPaddingTop) || 120;
          
          // If section is near the top of viewport (adjusted for nav)
          if (rect.top <= navHeight + 50 && rect.bottom >= navHeight + 50) {
            // Get the anchor id before this section
            const anchor = section.previousElementSibling;
            if (anchor && anchor.classList.contains('anchor-offset')) {
              currentSectionId = anchor.id;
            }
          }
        });
        
        // Update TOC links
        removeActiveClasses();
        tocLinks.forEach(link => {
          const href = link.getAttribute('href');
          if (href === '#' + currentSectionId || (href === '#top' && !currentSectionId)) {
            link.classList.add('active');
          }
        });
      }
      
      // Check on scroll
      window.addEventListener('scroll', checkActiveSection);
      
      // Initial check
      setTimeout(checkActiveSection, 100);
    }
    
    function setupSmoothScrolling() {
      const tocLinks = document.querySelectorAll('.toc a');
      
      tocLinks.forEach(link => {
        link.addEventListener('click', function(e) {
          const href = this.getAttribute('href');
          
          // Skip if it's an external link or empty
          if (!href || href.startsWith('http') || href === '#') return;
          
          e.preventDefault();
          
          const targetId = href.substring(1);
          let targetElement;
          
          if (targetId === 'top') {
            // Scroll to top of page
            window.scrollTo({
              top: 0,
              behavior: 'smooth'
            });
            return;
          }
          
          // Find the anchor offset element
          targetElement = document.getElementById(targetId);
          
          if (targetElement) {
            const navHeight = parseInt(document.documentElement.style.scrollPaddingTop) || 120;
            const elementPosition = targetElement.getBoundingClientRect().top;
            const offsetPosition = elementPosition + window.pageYOffset - navHeight;
            
            window.scrollTo({
              top: offsetPosition,
              behavior: 'smooth'
            });
          }
        });
      });
    }
  </script>
